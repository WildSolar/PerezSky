"""Effect of the brightness correction (Delta >= 0.2 for 1.065 < epsilon < 2.8; gendaylit).

For two typical meteorological years, compares perezsky with ``brightness_correction=True``
(default) and ``False``:

* share of daylight hours and of the diffuse irradiation affected;
* annual sky-diffuse and total irradiation on planes;
* hourly deviations of the sky-diffuse irradiance in the affected hours.

Usage:  python brightness_correction.py [path/to/pvgis_tmy.csv]   (results in results/)
The optional PVGIS TMY (columns ghi, dni, dhi; UTC index) is for Davos, as in the slopevf
project; pvlib's bundled TMY3 (Greensboro, NC) is always used.
"""

from __future__ import annotations

import sys
import warnings
from pathlib import Path

import numpy as np
import pandas as pd

import perezsky as ps

HERE = Path(__file__).parent
PLANES = [(0, 0), (35, 180), (90, 180), (90, 90), (90, 270), (90, 0)]
NAMES = ["horizontal", "35° S", "90° S", "90° E", "90° W", "90° N"]


def greensboro():
    import pvlib
    data, meta = pvlib.iotools.read_tmy3(Path(pvlib.__file__).parent / "data" / "723170TYA.CSV",
                                         map_variables=True)
    times = data.index - pd.Timedelta(minutes=30)                  # hour-ending -> mid-interval
    loc = pvlib.location.Location(meta["latitude"], meta["longitude"], altitude=meta["altitude"])
    return "Greensboro (TMY3)", data[["dni", "dhi"]].to_numpy(dtype=float), loc.get_solarposition(times), times


def davos(path):
    import pvlib
    df = pd.read_csv(path, index_col=0, parse_dates=True)
    times = df.index                                               # timestamps as given (UTC)
    loc = pvlib.location.Location(46.81, 9.85, altitude=2500)
    return "Davos (PVGIS TMY)", df[["dni", "dhi"]].to_numpy(dtype=float), loc.get_solarposition(times), times


def analyse(name, irr, sp, times):
    dni, dhi = irr.T
    zen, az = sp["apparent_zenith"].to_numpy(), sp["azimuth"].to_numpy()
    doy = times.dayofyear.to_numpy()
    day = (zen < 90) & (dni + dhi > 0)
    p = ps.perez_parameters(dni[day], dhi[day], zen[day], day_of_year=doy[day], brightness_correction=False)
    affected = (p.epsilon > 1.065) & (p.epsilon < 2.8) & (p.delta < 0.2)
    tilt, azim = np.array(PLANES).T
    res = {}
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        for corr in (True, False):
            res[corr] = ps.poa_irradiance(tilt, azim, dni, zen, az, dhi=dhi, albedo=0.2, day_of_year=doy,
                                          grid="low", brightness_correction=corr)
    lines = [f"### {name}", "",
             f"- Daylight hours: {day.sum()}; affected (1.065 < ε < 2.8 and Δ < 0.2): "
             f"{affected.sum()} ({affected.mean():.0%})",
             f"- Share of the annual diffuse irradiation in affected hours: "
             f"{dhi[day][affected].sum() / dhi[day].sum():.0%}; of the global: "
             f"{(dhi + dni * np.cos(np.radians(np.minimum(zen, 90))))[day][affected].sum() / (dhi + dni * np.cos(np.radians(np.minimum(zen, 90))))[day].sum():.0%}",
             f"- Δ in affected hours: median {np.median(p.delta[affected]):.3f}, "
             f"5th percentile {np.percentile(p.delta[affected], 5):.3f}", "",
             "| Plane | annual sky diffuse, change | annual total, change | hourly sky diffuse in affected hours: "
             "median change (5th..95th percentile) |", "|---|---|---|---|"]
    idx = np.flatnonzero(day)[affected]
    for k, n in enumerate(NAMES):
        s1, s0 = res[True]["sky"][:, k], res[False]["sky"][:, k]
        t1, t0 = res[True]["total"][:, k], res[False]["total"][:, k]
        ok = s0[idx] > 1.0
        rel = s1[idx][ok] / s0[idx][ok] - 1
        lines.append(f"| {n} | {s1.sum() / s0.sum() - 1:+.1%} | {t1.sum() / t0.sum() - 1:+.1%} | "
                     f"{np.median(rel):+.0%} ({np.percentile(rel, 5):+.0%} .. {np.percentile(rel, 95):+.0%}) |")
    return lines


def main():
    cases = [greensboro()]
    if len(sys.argv) > 1:
        cases.insert(0, davos(sys.argv[1]))
    lines = ["# Brightness correction (Δ ≥ 0.2 for 1.065 < ε < 2.8)", "",
             "Generated by `validation/brightness_correction.py`. Change = with correction (default, as "
             "gendaylit) relative to without. Albedo 0.2, grid `low`, Kasten-Young air mass, E0 = 1361 W/m² "
             "with Spencer correction.", ""]
    for c in cases:
        lines += analyse(*c) + [""]
    out = HERE / "results" / "brightness_correction.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
